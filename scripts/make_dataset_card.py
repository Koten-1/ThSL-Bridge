#!/usr/bin/env python3
"""Write research/DATASET_CARD.md: how the keypoint dataset is organised, what is in a file, how a sign was cut, who the
signers are (by code), and the counts. Every number comes from the files on disk, so re-run it when set B arrives.

  python3 scripts/make_dataset_card.py --keypoints ~/Downloads/ThSL_keypoints/setA ~/Downloads/ThSL_keypoints/setB \
      --orientation orientation.json --out research/DATASET_CARD.md

Only signer CODES appear in the card. The table that maps codes to people stays in a private file outside the repository.
"""
import argparse
import csv
import json
import sys
from collections import Counter, defaultdict
from pathlib import Path

import numpy as np

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
from word_audit import parse_name  # noqa: E402
import capture_rule  # noqa: E402


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--keypoints", nargs="+", required=True)
    ap.add_argument("--orientation", default=None, help="json {signer: {portrait: n, landscape: n}}")
    ap.add_argument("--out", default="research/DATASET_CARD.md")
    args = ap.parse_args()

    clips = []           # (signer, word, set)
    reports = {}
    for d in args.keypoints:
        d = Path(d)
        for f in sorted(d.rglob("*.npy")):
            s, w = parse_name(f)
            if w:
                clips.append((s, w, d.name))
        rp = d / "extract_report.csv"
        if rp.exists():
            reports[d.name] = list(csv.DictReader(open(rp, encoding="utf-8-sig")))
    if not clips:
        sys.exit("no keypoint files found")
    signers = sorted({c[0] for c in clips}); words = sorted({c[1] for c in clips})
    cell = Counter((c[0], c[1]) for c in clips)
    vocab = [w["th"] for w in json.loads((HERE / "vocab.json").read_text(encoding="utf-8"))["words"]]
    ori = json.loads(Path(args.orientation).read_text()) if args.orientation else {}
    o = capture_rule.DEFAULTS

    L = []
    P = L.append
    P("# ThSL Bridge keypoint dataset: structure and facts\n")
    P("Generated by `scripts/make_dataset_card.py` from the files on disk. Re-run it when data is added.\n")
    P(f"**{len(clips)} signs** (one sign per file), **{len(words)} words**, **{len(signers)} signers** ({', '.join(signers)}). "
      f"Sets read: {', '.join(sorted({c[2] for c in clips}))}.\n")
    P("## 1. What the dataset is\n")
    P("Sequences of hand landmark numbers, not images. Each file is one sign made by one signer. Videos and faces are not part of the dataset; "
      "the original videos stay with the project team under the consent form.\n")
    P("## 2. Folders and file names\n")
    P("```\nkeypoints/\n  <signer code>/\n    <word>/\n      <signer>_<word>_t<take>r<NN>.npy\n  extract_report.csv\n```\n")
    P("- `<signer>`: a code such as S01. The table that maps codes to people is kept in a private file outside the repository (the consent form promises codes, not names).")
    P("- `<word>`: the Thai word exactly as written in `scripts/vocab.json`.")
    P("- `t<take>`: the number of the video the sign came from. `r<NN>`: the sign number inside that video (1 when a video holds one sign).")
    P("- `extract_report.csv`: one row per source video (signs found, frame rate, why a video gave nothing). It holds no original file names.\n")
    P("## 3. What is inside a file\n")
    P("A NumPy array of shape **(30, 126)**, `float32`.\n")
    P("- 30 frames. The frames the hand was tracked in during the sign are resampled to 30 evenly spaced frames. The real duration is NOT stored: a fast and a slow sign look the same length.")
    P("- 126 numbers per frame = two hand slots of 63. Slot 1 (columns 0 to 62) is the hand MediaPipe labels *Left*, slot 2 (columns 63 to 125) the hand it labels *Right*. Each slot is 21 landmarks times (x, y, z).")
    P("- x and y are normalised to the picture width and height (0 to 1). z is depth relative to the wrist, in roughly the same scale as x, and is mostly negative for a hand facing the camera.")
    P("- A hand that is not detected in a frame is **all zeros** in its slot. Zero means absent, never a real position.")
    P("- *Left* and *Right* are MediaPipe's labels, which assume a mirrored picture. They are not reliably the signer's anatomical hands: a left-handed signer, or a video saved mirrored by the camera app, puts the active hand in the other slot. Training handles this with mirror augmentation (swap the slots and flip x).")
    P("- Landmarks are NOT normalised for camera distance or position. Portrait and landscape videos have different normalised coordinates (see section 6).\n")
    P("## 4. How a sign was cut and how the numbers were made\n")
    P("- Hand tracking: MediaPipe Hands 0.10.14 (Python), up to 2 hands, detection confidence 0.5, frames shrunk to at most 720 px on the long side before tracking.")
    P(f"- Where a sign starts and stops: `scripts/capture_rule.py` (the same rule runs in the web app, `capture_rule.js`). A sign starts when the hand moves (change over {o['win_ms']} ms of at least {o['move_t']}) and ends after {o['still_ms']} ms of stillness, or when the hand is gone for {o['missing_ms']} ms, or when the recording ends. About {o['lead_ms']} ms before the first movement is kept. A capture shorter than {o['min_ms']} ms is discarded.")
    P("- Videos are used as they are: no rotation, no cropping, no editing.\n")
    P("## 5. Signers, words and counts\n")
    P("Number of signs per word and signer:\n")
    P("| word | " + " | ".join(signers) + " | total |\n|---|" + "---|" * (len(signers) + 1))
    for w in sorted(words, key=lambda x: vocab.index(x) if x in vocab else 99):
        row = [cell.get((s, w), 0) for s in signers]
        P(f"| {w} | " + " | ".join(str(x) for x in row) + f" | {sum(row)} |")
    P("| **total** | " + " | ".join(f"**{sum(cell.get((s, w), 0) for w in words)}**" for s in signers) + f" | **{len(clips)}** |\n")
    hearing = [s for s in signers if s.startswith("H")]
    deaf = [s for s in signers if s.startswith("S")]
    if hearing:
        P(f"Signer groups: **{', '.join(deaf)}** are deaf signers (the target users). **{', '.join(hearing)}** are hearing signers (team members and friends, videos from the first project phase, re-cut with the same capture rule); they are used only for the words where deaf signers are missing: "
          + ", ".join(sorted({w for w in words if any(cell.get((h, w), 0) for h in hearing)})) + ". A model trained on them has not been evaluated on the main deaf signers for those words.\n")
    full = [s for s in signers if sum(cell.get((s, w), 0) for w in words) >= 500]
    P(f"Signers with at least 500 signs: {', '.join(full) if full else 'none'}. A signer with fewer than about 20 signs cannot be held out in leave-one-signer-out evaluation and is used for training only.\n")
    thin = [w for w in words if sum(1 for s in signers if cell.get((s, w), 0) >= 20) < 3]
    if thin:
        P("Words covered by fewer than 3 signers with at least 20 signs: " + ", ".join(thin) + ". These are hard to evaluate and hard to learn in a signer-independent way.\n")
    for name, rows in reports.items():
        c = Counter(r["status"] for r in rows)
        fps = Counter(r.get("fps", "") for r in rows)
        P(f"Set `{name}`: {len(rows)} source videos, {sum(int(r.get('kept') or 0) for r in rows)} signs found; videos that gave no sign: {sum(1 for r in rows if int(r.get('kept') or 0) == 0)}; frame rates: " + ", ".join(f"{k} fps: {v}" for k, v in fps.most_common()) + ".")
    P("")
    if ori:
        P("## 6. Camera orientation per signer\n")
        P("| signer | landscape | portrait |\n|---|---|---|")
        for s in sorted(ori):
            P(f"| {s} | {ori[s].get('landscape', 0)} | {ori[s].get('portrait', 0)} |")
        P("\nBecause x and y are normalised by the picture width and height, a portrait and a landscape video of the same sign give different numbers. "
          "On earlier data the same signer's portrait and landscape clips were about 4 times further apart than clips in the same orientation. "
          "A signer filmed only in portrait therefore looks like a different signer to the model. Check this before reading any per-signer result.\n")
    P("## 7. Known limits\n")
    P("- Few full signers: most words have 2 or 3 signers with enough signs, so leave-one-signer-out trains on 1 or 2 signers per fold.")
    P("- Some words differ between signers (dictionary variants, personal style). The EDA (`scripts/eda_report.py`) lists them.")
    P("- Left and right slots follow MediaPipe's labels, see section 3.")
    P("- Participants are adult volunteers with a signed consent form. No formal ethics-committee review took place before recording (see the paper's limitations).")
    P("- Face landmarks are not in this dataset.\n")
    P("## 8. Rebuilding it from the videos\n")
    P("```\npython3 scripts/rename_takes.py FOLDER... --signer-map signers.csv --plan rename_plan.csv\npython3 scripts/extract_from_plan.py rename_plan.csv --out keypoints\npython3 scripts/eda_report.py keypoints --out eda\n```")
    Path(args.out).write_text("\n".join(L), encoding="utf-8")
    print(f"wrote {args.out}: {len(clips)} signs, {len(words)} words, {len(signers)} signers")


if __name__ == "__main__":
    main()
